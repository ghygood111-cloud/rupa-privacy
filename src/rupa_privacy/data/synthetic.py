FEATURE_NAMES = [
    "wastewater",
    "cod",
    "electricity",
    "ore_input",
    "fresh_water",
    "runtime",
    "dust",
    "circulating_water",
    "province",
    "scale",
]

PUBLIC_BOUNDS = {
    "wastewater": (1000.0, 7000.0),
    "cod": (20.0, 180.0),
    "electricity": (5000.0, 35000.0),
    "ore_input": (250.0, 1600.0),
    "fresh_water": (20.0, 250.0),
    "runtime": (5.0, 16.0),
    "dust": (0.0, 20.0),
    "circulating_water": (800.0, 7000.0),
}

PUBLIC_CATEGORIES = {
    # Ordering matches np.unique() in the historical fixed-seed workflow.
    "province": ["hebei", "liaoning", "neimenggu", "shanxi"],
    "scale": ["large", "medium", "small"],
}


def generate_example_dataset(n_rows=1000, seed=42):
    """Return the synthetic table generated by the current root step 1 logic."""
    rng = np.random.RandomState(seed)
    production = rng.uniform(100, 500, n_rows)
    wastewater = production * 12.1 + rng.normal(0, production * 12.1 * 0.03, n_rows)
    cod = wastewater * 0.025 + rng.normal(0, wastewater * 0.025 * 0.01, n_rows)
    electricity = production * 60.0 + rng.normal(0, production * 60.0 * 0.05, n_rows)
    ore_input = production * 2.88 + rng.normal(0, production * 2.88 * 0.05, n_rows)
    fresh_water = production * 0.4 + rng.normal(0, production * 0.4 * 0.05, n_rows)
    runtime = 8 + production * 0.01 + rng.normal(0, 1, n_rows)
    dust = 5 + production * 0.01 + rng.normal(0, 2, n_rows)
    circulating_water = production * 12.0 + rng.normal(
        0, production * 12.0 * 0.10, n_rows
    )
    province = rng.choice(["hebei", "shanxi", "liaoning", "neimenggu"], n_rows)
    scale = rng.choice(["large", "medium", "small"], n_rows, p=[0.3, 0.5, 0.2])
    return pd.DataFrame(
        {
            "enterprise_id": ["enterprise_{0}_{1}".format(seed, index) for index in range(n_rows)],
            "production": production,
            "wastewater": wastewater,
            "cod": cod,
            "electricity": electricity,
            "ore_input": ore_input,
            "fresh_water": fresh_water,
            "runtime": runtime,
            "dust": dust,
            "circulating_water": circulating_water,
            "province": province,
            "scale": scale,
        }
    )


def generate_example_pair(n_release=1000, n_calibration=1000):
    """Return disjoint deterministic release and calibration samples."""
    release = generate_example_dataset(n_rows=n_release, seed=42)
    calibration = generate_example_dataset(n_rows=n_calibration, seed=314159)
    return calibration, release


